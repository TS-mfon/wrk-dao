"""Keccak-256 — vendored, pure Python, no dependencies.

Why this file exists at all
---------------------------
`docs/CANONICAL.md` §1.3 fixes the digest at keccak256 because Solidity verifies
these hashes and keccak256 is a single EVM opcode. The GenLayer documentation does
not say whether a hashing primitive is available inside the GenVM sandbox, nor
which standard-library modules the sandbox permits, so depending on one would be
depending on an undocumented runtime surface. This implementation needs nothing
but integers and bytes.

The trap this also avoids
-------------------------
`hashlib.sha3_256` is **not** keccak256. SHA3-256 was standardised with a
different domain-separation byte (0x06) than original Keccak (0x01), so the two
produce completely different digests for the same input. Reaching for `hashlib`
because it is already imported is the single most likely way to fork this
protocol's hashes, and it would fail silently: every digest would be
self-consistent and every one would disagree with Base.

Correctness is established by `contracts/genlayer/tests/lib/verify_hashing.py`,
which reproduces all 41 digests in `fixtures/canonical-vectors.json`. Those were
generated by viem, cross-checked against Foundry's `cast keccak` and against
solc's own `keccak256` inside a Solidity test — three independent implementations,
none sharing a lineage with this one.
"""

from __future__ import annotations

_MASK64 = (1 << 64) - 1

#: Keccak-f[1600] round constants.
_ROUND_CONSTANTS = (
    0x0000000000000001,
    0x0000000000008082,
    0x800000000000808A,
    0x8000000080008000,
    0x000000000000808B,
    0x0000000080000001,
    0x8000000080008081,
    0x8000000000008009,
    0x000000000000008A,
    0x0000000000000088,
    0x0000000080008009,
    0x000000008000000A,
    0x000000008000808B,
    0x800000000000008B,
    0x8000000000008089,
    0x8000000000008003,
    0x8000000000008002,
    0x8000000000000080,
    0x000000000000800A,
    0x800000008000000A,
    0x8000000080008081,
    0x8000000000008080,
    0x0000000080000001,
    0x8000000080008008,
)

#: Rotation offsets, indexed ``_ROTATION[x][y]``.
_ROTATION = (
    (0, 36, 3, 41, 18),
    (1, 44, 10, 45, 2),
    (62, 6, 43, 15, 61),
    (28, 55, 25, 21, 56),
    (27, 20, 39, 8, 14),
)

#: Keccak-256: capacity 512 bits, so the rate is (1600 - 512) / 8 = 136 bytes.
_RATE_BYTES = 136
_OUTPUT_BYTES = 32

#: Original Keccak padding. SHA3 uses 0x06 here; using it would be a different
#: hash function wearing the same name.
_DOMAIN_BYTE = 0x01


def _rotl64(value: int, shift: int) -> int:
    shift %= 64
    if shift == 0:
        return value & _MASK64
    return ((value << shift) | (value >> (64 - shift))) & _MASK64


def _keccak_f1600(lanes: list[list[int]]) -> None:
    """The permutation, applied in place. ``lanes[x][y]`` holds lane (x, y)."""
    for round_constant in _ROUND_CONSTANTS:
        # θ — parity of each column, mixed into every lane of the neighbouring ones.
        column_parity = [
            lanes[x][0] ^ lanes[x][1] ^ lanes[x][2] ^ lanes[x][3] ^ lanes[x][4] for x in range(5)
        ]
        theta = [
            column_parity[(x - 1) % 5] ^ _rotl64(column_parity[(x + 1) % 5], 1) for x in range(5)
        ]
        for x in range(5):
            for y in range(5):
                lanes[x][y] ^= theta[x]

        # ρ (rotate each lane) and π (permute lane positions), together.
        shuffled = [[0] * 5 for _ in range(5)]
        for x in range(5):
            for y in range(5):
                shuffled[y][(2 * x + 3 * y) % 5] = _rotl64(lanes[x][y], _ROTATION[x][y])

        # χ — the only non-linear step.
        for x in range(5):
            for y in range(5):
                lanes[x][y] = shuffled[x][y] ^ (
                    (~shuffled[(x + 1) % 5][y] & _MASK64) & shuffled[(x + 2) % 5][y]
                )

        # ι
        lanes[0][0] ^= round_constant


def _absorb_block(lanes: list[list[int]], block: bytes) -> None:
    for offset in range(0, _RATE_BYTES, 8):
        lane = int.from_bytes(block[offset : offset + 8], "little")
        index = offset // 8
        lanes[index % 5][index // 5] ^= lane
    _keccak_f1600(lanes)


def keccak256(data: bytes) -> bytes:
    """Return the 32-byte Keccak-256 digest of ``data``."""
    if isinstance(data, (bytearray, memoryview)):
        data = bytes(data)
    if not isinstance(data, bytes):
        raise TypeError(f"keccak256 takes bytes, got {type(data).__name__}")

    lanes = [[0] * 5 for _ in range(5)]

    full_blocks = len(data) // _RATE_BYTES
    for index in range(full_blocks):
        _absorb_block(lanes, data[index * _RATE_BYTES : (index + 1) * _RATE_BYTES])

    # pad10*1, with the Keccak domain byte. When exactly one byte of the block is
    # free, the two pad bits share it and the byte is 0x81.
    tail = bytearray(data[full_blocks * _RATE_BYTES :])
    tail.append(_DOMAIN_BYTE)
    while len(tail) < _RATE_BYTES:
        tail.append(0x00)
    tail[_RATE_BYTES - 1] |= 0x80
    _absorb_block(lanes, bytes(tail))

    out = bytearray()
    while len(out) < _OUTPUT_BYTES:
        for index in range(_RATE_BYTES // 8):
            if len(out) >= _OUTPUT_BYTES:
                break
            out.extend(lanes[index % 5][index // 5].to_bytes(8, "little"))
        if len(out) < _OUTPUT_BYTES:  # unreachable for a 32-byte output
            _keccak_f1600(lanes)
    return bytes(out[:_OUTPUT_BYTES])


def keccak256_hex(data: bytes) -> str:
    """Return the digest as a ``0x``-prefixed lowercase hex string."""
    return "0x" + keccak256(data).hex()
